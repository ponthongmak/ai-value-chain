<#
  build-analysis.ps1 — bundle the data files into scripts the page can load even when
  opened straight from disk (file://):
    analysis\*.json        -> ai-analysis.js   (window.AI_ANALYSIS)
    news\L*.json           -> ai-news.js       (window.AI_NEWS)
    data\fundamentals.json -> fundamentals.js  (window.FUND)
#>
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'common.ps1')

# Several jobs can finish at once (and Google Drive may hold a file briefly): retry on a lock.
function Write-Bundle([string]$name, [string]$js) {
  $target = Join-Path $AiRoot $name
  for ($try = 1; ; $try++) {
    try { [IO.File]::WriteAllText($target, $js, $Utf8); break }
    catch { if ($try -ge 10) { throw }; Start-Sleep -Milliseconds (300 * $try) }
  }
}
function Get-Parts([string]$dir, [string]$filter) {
  $parts = @()
  if (Test-Path $dir) {
    Get-ChildItem $dir -Filter $filter -File | Sort-Object Name | ForEach-Object {
      $txt = [IO.File]::ReadAllText($_.FullName, $Utf8).Trim()
      try { $null = $txt | ConvertFrom-Json } catch { Write-Warning "Skipping invalid JSON: $($_.Name)"; return }
      $parts += ('"' + $_.BaseName + '":' + $txt)
    }
  }
  return ,$parts
}
$head = "/* Generated by tools/build-analysis.ps1 - do not edit by hand. */`n"

$a = Get-Parts $AiDir '*.json'
Write-Bundle 'ai-analysis.js' ($head + "window.AI_ANALYSIS = {" + ($a -join ",`n") + "};`n")
$n = Get-Parts $NewsDir 'L*.json'
Write-Bundle 'ai-news.js' ($head + "window.AI_NEWS = {" + ($n -join ",`n") + "};`n")
$fund = Join-Path $DataDir 'fundamentals.json'
$f = if (Test-Path $fund) { [IO.File]::ReadAllText($fund, $Utf8).Trim() } else { 'null' }
Write-Bundle 'fundamentals.js' ($head + "window.FUND = $f;`n")
# Judging panel: each member's scores per sector + the panel weights (the page averages them).
$jr = Get-Parts (Join-Path $DataDir 'judge') '*.json'
$panel = @(Get-Judges | ForEach-Object { [ordered]@{ profile = $_.profile; model = $_.model; effort = $_.effort; weight = $_.weight } }) | ConvertTo-Json -Depth 4 -Compress
if (-not $panel) { $panel = '[]' } elseif (-not $panel.StartsWith('[')) { $panel = "[$panel]" }
Write-Bundle 'judgments.js' ($head + "window.JUDGE = {panel:$panel, runs:{" + ($jr -join ",`n") + "}};`n")
Write-Host "ai-analysis.js: $($a.Count) stock(s) | ai-news.js: $($n.Count) layer(s) | fundamentals.js: $(if ($f -ne 'null') { 'yes' } else { 'none' }) | judgments.js: $($jr.Count) run(s)"
